//go:build codegen

// Command make_commands generates a commands table based on the
// provided JSON list as glob patterns.
//
// usage: make_commands.go [--] <output.go> <table> <glob>...
// example: go run -tags codegen make_commands.go commands_redis.go RedisCommands ../lib/redis/src/commands/*.json
package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strconv"
	"strings"
)

// jsonBool accepts the JSON booleans and their string form.
// It accepts `true`, `false`, `"true"`, and `"false"`.
type jsonBool bool

func (b *jsonBool) UnmarshalJSON(data []byte) error {
	var v bool
	if err := json.Unmarshal(data, &v); err == nil {
		*b = jsonBool(v)
		return nil
	}
	var s string
	if err := json.Unmarshal(data, &s); err == nil {
		*b = s == "true"
		return nil
	}
	return fmt.Errorf("commands: not a boolean: %s", data)
}

// argSpec represents one argument of the command JSON.
type argSpec struct {
	Name          string     `json:"name"`
	Type          string     `json:"type"`
	Token         string     `json:"token"`
	DisplayText   string     `json:"display_text"`
	Optional      jsonBool   `json:"optional"`
	Multiple      jsonBool   `json:"multiple"`
	MultipleToken jsonBool   `json:"multiple_token"`
	Container     string     `json:"container"`
	Arguments     []*argSpec `json:"arguments"`
}

// keySpec represents one key specification of the command JSON.
type keySpec struct {
	Flags       []string `json:"flags"`
	BeginSearch struct {
		Index struct {
			Pos int `json:"pos"`
		} `json:"index"`
		Keyword struct {
			Keyword   string `json:"keyword"`
			StartFrom int    `json:"startfrom"`
		} `json:"keyword"`
	} `json:"begin_search"`
	FindKeys struct {
		Range struct {
			LastKey int `json:"lastkey"`
			Step    int `json:"step"`
			Limit   int `json:"limit"`
		} `json:"range"`
		KeyNum struct {
			KeyNumIdx  int `json:"keynumidx"`
			FirstKey   int `json:"firstkey"`
			KeyNumStep int `json:"keystep"`
		} `json:"keynum"`
	} `json:"find_keys"`
}

// command represents one command of the command JSON.
type command struct {
	Name         string     `json:"-"`
	Container    string     `json:"container"`
	Arity        int        `json:"arity"`
	CommandFlags []string   `json:"command_flags"`
	KeySpecs     []keySpec  `json:"key_specs"`
	Arguments    []*argSpec `json:"arguments"`
	Subcommands  []*command `json:"-"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "commands/make_commands.go:", err)
		os.Exit(1)
	}
}

func run() error {
	args := os.Args[1:]
	for len(args) > 0 && args[0] == "--" {
		args = args[1:]
	}
	if len(args) < 3 {
		return errors.New("usage: make_commands.go [--] <output.go> <table> <glob>...")
	}
	file, table, globs := args[0], args[1], args[2:]

	commands := map[string]*command{}
	subcommands := map[string][]*command{}
	for _, glob := range globs {
		files, err := filepath.Glob(glob)
		if err != nil {
			return err
		}
		if len(files) == 0 {
			return fmt.Errorf("no files match %s", glob)
		}
		for _, f := range files {
			if err := readFile(commands, subcommands, f); err != nil {
				return err
			}
		}
	}

	names := make([]string, 0, len(commands))
	for name := range commands {
		names = append(names, name)
	}
	sort.Strings(names)

	for name, subs := range subcommands {
		sort.Slice(subs, func(i, j int) bool { return subs[i].Name < subs[j].Name })
		commands[name].Subcommands = subs
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by commands/make_commands.go; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// The table mirrors the command JSON of %s.\n", strings.Join(globs, " "))
	fmt.Fprintf(&b, "\npackage commands\n\n")
	fmt.Fprintf(&b, "// %s holds the commands with their argument specs.\n", table)
	fmt.Fprintf(&b, "var %s = Table{\n", table)
	for _, k := range slices.Sorted(maps.Keys(commands)) {
		c := commands[k]
		writeCommand(&b, strconv.Quote(c.Name), c, 1)
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("formatting %s: %w", table, err)
	}
	if err := os.WriteFile(file, src, 0644); err != nil {
		return err
	}
	return nil
}

// readFile reads the commands of one JSON file into the table.
func readFile(commands map[string]*command, subcommands map[string][]*command, file string) error {
	data, err := os.ReadFile(file)
	if err != nil {
		return err
	}
	// Each command has a key in the root.
	var cmds map[string]*command
	if err := json.Unmarshal(data, &cmds); err != nil {
		return fmt.Errorf("%s: %w", filepath.Base(file), err)
	}
	for name, c := range cmds {
		c.Name = name
		if c.Container != "" {
			subcommands[c.Container] = append(subcommands[c.Container], c)
		} else {
			commands[c.Name] = c
		}
	}
	return nil
}

func writeCommand(b *strings.Builder, key string, c *command, depth int) {
	indent := strings.Repeat("\t", depth)
	if key != "" {
		fmt.Fprintf(b, "%s%s: {\n", indent, key)
	} else {
		fmt.Fprintf(b, "%s{\n", indent)
	}
	fmt.Fprintf(b, "%s\tName: %s,\n", indent, strconv.Quote(c.Name))
	if c.Arity != 0 {
		fmt.Fprintf(b, "%s\tArity:    %d,\n", indent, c.Arity)
	}
	if len(c.CommandFlags) > 0 {
		flags := make([]string, len(c.CommandFlags))
		for i, f := range c.CommandFlags {
			flags[i] = strings.ToLower(f)
		}
		fmt.Fprintf(b, "%s\tFlags:    []string{%s},\n", indent, quoteList(flags))
	}
	if len(c.Subcommands) > 0 {
		fmt.Fprintf(b, "%s\tSubcommands: []*Command{\n", indent)
		for _, sub := range c.Subcommands {
			writeCommand(b, "", sub, depth+2)
		}
		fmt.Fprintf(b, "%s\t},\n", indent)
	}
	if len(c.KeySpecs) > 0 {
		fmt.Fprintf(b, "%s\tKeySpecs: []KeySpec{\n", indent)
		for _, ks := range c.KeySpecs {
			writeKeySpec(b, &ks, depth+2)
		}
		fmt.Fprintf(b, "%s\t},\n", indent)
	}
	if len(c.Arguments) > 0 {
		fmt.Fprintf(b, "%s\tArgs: []ArgSpec{\n", indent)
		for _, a := range c.Arguments {
			writeArg(b, a, depth+2)
		}
		fmt.Fprintf(b, "%s\t},\n", indent)
	}
	fmt.Fprintf(b, "%s},\n", indent)
}

func writeKeySpec(b *strings.Builder, ks *keySpec, depth int) {
	indent := strings.Repeat("\t", depth)
	fmt.Fprintf(b, "%s{\n", indent)
	if len(ks.Flags) > 0 {
		fmt.Fprintf(b, "%s\tFlags: []string{%s},\n", indent, quoteList(ks.Flags))
	}
	switch {
	case ks.BeginSearch.Index.Pos != 0 || ks.BeginSearch.Keyword.Keyword == "":
		fmt.Fprintf(b, "%s\tBeginSearch: BeginSearchIndex{Pos: %d},\n", indent, ks.BeginSearch.Index.Pos)
	default:
		fmt.Fprintf(b, "%s\tBeginSearch: BeginSearchKeyword{Keyword: %s, Start: %d},\n", indent, strconv.Quote(ks.BeginSearch.Keyword.Keyword), ks.BeginSearch.Keyword.StartFrom)
	}
	if r := ks.FindKeys.Range; r.LastKey != 0 || r.Step != 0 || r.Limit != 0 {
		fmt.Fprintf(b, "%s\tFindKeys: FindKeysRange{Last: %d, Step: %d, Limit: %d},\n", indent, r.LastKey, r.Step, r.Limit)
	} else {
		k := ks.FindKeys.KeyNum
		fmt.Fprintf(b, "%s\tFindKeys: FindKeysKeynum{KeynumIdx: %d, First: %d, Step: %d},\n", indent, k.KeyNumIdx, k.FirstKey, k.KeyNumStep)
	}
	fmt.Fprintf(b, "%s},\n", indent)
}

func writeArg(b *strings.Builder, a *argSpec, depth int) {
	indent := strings.Repeat("\t", depth)
	fmt.Fprintf(b, "%s{\n", indent)
	field := func(name, value string) {
		if value != "" {
			fmt.Fprintf(b, "%s\t%s: %s,\n", indent, name, strconv.Quote(value))
		}
	}
	field("Name", a.Name)
	field("Type", a.Type)
	field("Token", a.Token)
	field("Text", a.DisplayText)
	if a.Optional {
		fmt.Fprintf(b, "%s\tOptional: true,\n", indent)
	}
	if a.Multiple {
		fmt.Fprintf(b, "%s\tMultiple: true,\n", indent)
	}
	if a.MultipleToken {
		fmt.Fprintf(b, "%s\tMultipleToken: true,\n", indent)
	}
	if len(a.Arguments) > 0 {
		fmt.Fprintf(b, "%s\tArgs: []ArgSpec{\n", indent)
		for _, sub := range a.Arguments {
			writeArg(b, sub, depth+2)
		}
		fmt.Fprintf(b, "%s\t},\n", indent)
	}
	fmt.Fprintf(b, "%s},\n", indent)
}

func quoteList(list []string) string {
	quoted := make([]string, len(list))
	for i, s := range list {
		quoted[i] = strconv.Quote(s)
	}
	return strings.Join(quoted, ", ")
}
