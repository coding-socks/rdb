//go:build codegen
// +build codegen

// This program generates compress.go.

package main

import (
	"bytes"
	"golang.org/x/tools/imports"
	"io"
	"io/ioutil"
	"log"
	"os"
	"strings"
	"text/template"
)

var header = []byte(`// Code generated by go run make_compress.go. DO NOT EDIT.

package lzf

`)

func main() {
	filename := "compress.go"
	buf := bytes.NewBuffer(header)

	gen(buf)

	out, err := imports.Process(filename, buf.Bytes(), nil)
	if err != nil {
		io.Copy(os.Stdout, bytes.NewReader(buf.Bytes()))
		log.Fatal(err)
	}

	err = ioutil.WriteFile(filename, out, 0666)
	if err != nil {
		log.Fatal(err)
	}
}

func gen(w io.Writer) {
	flavors := []struct {
		Name  string
		Idx   string
		Store string
	}{
		{
			Name: "fast",
			Idx:  `(((hval ^ (hval << 5)) >> (3*8 - c.hlog)) - hval*5) & (c.hsize - 1)`,
			Store: `
			iin -= l + 1

			for ok := true; ok; ok = l > -1 {
				hval = next(hval, input, iin)
				htab[{{.idx}}] = uint32(iin)
				iin++
				l--
			}`,
		},
		{
			Name: "veryFast",
			Idx:  `((hval >> (3*8 - c.hlog)) - hval*5) & (c.hsize - 1)`,
			Store: `
			iin -= 2
			hval = frst(input, iin)

			hval = next(hval, input, iin)
			htab[{{.idx}}] = uint32(iin)
			iin++

			hval = next(hval, input, iin)
			htab[{{.idx}}] = uint32(iin)
			iin++`,
		},
		{
			Name: "ultraFast",
			Idx:  `((hval >> (3*8 - c.hlog)) - hval) & (c.hsize - 1)`,
			Store: `
			iin--
			hval = frst(input, iin)

			hval = next(hval, input, iin)
			htab[{{.idx}}] = uint32(iin)
			iin++`,
		},
	}
	tmpl, err := template.New("compress").Parse(`
func (c LZF) compress{{.name}}(input []byte, output []byte) (int, error)  {
	var (
		lin, lout      = len(input), len(output)
		iin, iout, lit = 0, 1, 0
	)
	if lin == 0 {
		return 0, nil
	}
	if lin == 1 {
		return 0, ErrINVAL
	}
	if lout == 0 {
		return 0, Err2BIG
	}
	htab := make([]uint32, c.hsize)
	hval := frst(input, iin)

	for iin < (lin - 2) {
		hval = next(hval, input, iin)
		hslot := {{.idx}}
		iref := int(htab[hslot])
		htab[hslot] = uint32(iin)

		off := iin - iref - 1

		if off < maxOff &&
			iref > 0 &&
			input[iref+2] == input[iin+2] &&
			input[iref+1] == input[iin+1] &&
			input[iref] == input[iin] { // match found at iref++

			l := 2
			maxLen := lin - iin - l
			if maxLen > maxRef {
				maxLen = maxRef
			}

			if (iout + 3 + 1) >= lout { // first a faster conservative test
				var nlit int
				if lit == 0 {
					nlit = 1
				}
				if (iout - nlit + 3 + 1) >= lout { // second the exact but rare test
					return 0, Err2BIG
				}
			}

			output[iout-lit-1] = byte(lit - 1) // stop run
			if lit == 0 {
				iout -= 1 // undo run if length is zero
			}

			l++
			for l < maxLen && input[iref+l] == input[iin+l] {
				l++
			}

			l -= 2 // l is now #octets - 1
			iin++

			if l < 7 {
				output[iout] = byte((off >> 8) + (l << 5))
				iout++
			} else {
				output[iout] = byte((off >> 8) + (7 << 5))
				iout++
				output[iout] = byte(l - 7)
				iout++
			}

			output[iout] = byte(off)

			iout += 2
			lit = 0 // start run

			iin += l + 1

			if iin >= lin-2 {
				break
			}

			{{.store}}
		} else {
			if iout >= lout {
				return 0, Err2BIG
			}

			lit++
			output[iout] = input[iin]
			iout++
			iin++

			if lit == maxLit {
				output[iout-lit-1] = byte(lit - 1) // stop run
				lit = 0
				iout++ // start run
			}
		}
	}

	if iout+3 > lout { // at most 3 bytes can be missing here
		return 0, Err2BIG
	}

	for iin < lin {
		lit++
		output[iout] = input[iin]
		iout++
		iin++

		if lit == maxLit {
			output[iout-lit-1] = byte(lit - 1) // stop run
			lit = 0
			iout++ // start run
		}
	}

	output[iout-lit-1] = byte(lit - 1) // end run
	if lit == 0 {
		iout-- // undo run if length is zero
	}

	return iout, nil
}
`)
	if err != nil {
		panic(err)
	}
	for _, flavor := range flavors {
		t, err := template.New(flavor.Name).Parse(flavor.Store)
		if err != nil {
			panic(err)
		}
		var buf bytes.Buffer
		t.Execute(&buf, map[string]string{
			"name": strings.Title(flavor.Name),
			"idx":  flavor.Idx,
		})
		err = tmpl.Execute(w, map[string]string{
			"name":  strings.Title(flavor.Name),
			"idx":   flavor.Idx,
			"store": buf.String(),
		})
		if err != nil {
			panic(err)
		}
	}
}
